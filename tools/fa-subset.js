#!/usr/bin/env node
/*
 * Builds assets/libs/fontawesome/icons.min.js: the full Font Awesome Free
 * bundle (all.min.js, same folder) with every icon the site doesn't use
 * removed. The rendering code is untouched, so icons behave exactly as
 * before (each <i class="fas fa-x"> is swapped for an inline <svg>).
 *
 * Also writes assets/js/fa-loader.js, which every page runs: it loads the
 * subset, or the full all.min.js when the page uses an icon the subset
 * lacks, so a new icon always shows even before this script is rerun.
 *
 * Nothing to do by hand: .github/workflows/icon-subset.yml runs this on every
 * push to main that could change the icons and commits the result. To run
 * it locally:   node tools/fa-subset.js
 *
 * Icon names are found by scanning the site's templates, data, pages and
 * scripts for "fa-<name>". An icon whose name is built at run time (not
 * written out anywhere) must be added to EXTRA below.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'assets/libs/fontawesome/all.min.js');
const OUT = path.join(ROOT, 'assets/libs/fontawesome/icons.min.js');

// Icons the scan can't see (names assembled in code). Plain names, no "fa-".
const EXTRA = [];

// Folders and root files scanned for icon names.
const SCAN_DIRS = ['_includes', '_layouts', '_data', '_posters', '_videos', '_publications', 'assets/js'];
const SCAN_EXT = /\.(html|md|ya?ml|js|json|liquid)$/;
const SKIP_ROOT_FILES = new Set(['CLAUDE.md', 'CHANGELOG.md', 'README.md']);

function walk(dir, out) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (SCAN_EXT.test(e.name)) out.push(p);
  }
  return out;
}

const files = [];
SCAN_DIRS.forEach(d => walk(path.join(ROOT, d), files));
fs.readdirSync(ROOT).forEach(f => {
  if (SCAN_EXT.test(f) && !SKIP_ROOT_FILES.has(f)) files.push(path.join(ROOT, f));
});

const wanted = new Set(EXTRA);
for (const f of files) {
  for (const m of fs.readFileSync(f, 'utf8').matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) wanted.add(m[1]);
}

const src = fs.readFileSync(SRC, 'utf8');

// Icon entries look like  name:[w,h,[aliases],"unicode","path"]  or
// "quoted-name":[...]. Find each one, read it to its closing bracket
// (string-aware), and decide whether to keep it.
const startRe = /([,{])("([a-z0-9-]+)"|([a-z][a-z0-9]*)):\[(\d+),(\d+),\[/g;

function endOfArray(s, i) { // s[i] === '['
  let depth = 0;
  for (let j = i; j < s.length; j++) {
    const c = s[j];
    if (c === '"' || c === "'") {
      j++;
      while (s[j] !== c) { if (s[j] === '\\') j++; j++; }
    } else if (c === '[') depth++;
    else if (c === ']') { depth--; if (depth === 0) return j; }
  }
  throw new Error('unbalanced array at ' + i);
}

const found = new Set();
let out = '';
let last = 0;
let kept = 0;
let dropped = 0;
let m;
while ((m = startRe.exec(src))) {
  const name = m[3] || m[4];
  const arrStart = m.index + m[0].indexOf(':[') + 1;
  const arrEnd = endOfArray(src, arrStart);
  const body = src.slice(arrStart, arrEnd + 1);
  const aliases = (body.match(/^\[\d+,\d+,\[([^\]]*)\]/) || [, ''])[1]
    .split(',').map(a => a.replace(/"/g, '')).filter(a => /^[a-z]/.test(a));
  const names = [name, ...aliases];
  const keep = names.some(n => wanted.has(n));
  if (keep) {
    names.forEach(n => { if (wanted.has(n)) found.add(n); });
    kept++;
  } else {
    // Drop "name:[...]" plus one separating comma, keeping the object valid.
    const entryStart = m.index + 1; // after the leading , or {
    let entryEnd = arrEnd + 1;
    if (src[entryEnd] === ',') entryEnd++; // trailing comma goes with it
    out += src.slice(last, entryStart);
    last = entryEnd;
    dropped++;
  }
  startRe.lastIndex = arrEnd + 1;
}
out += src.slice(last);
// An object whose last kept entry was followed by a dropped one ends in ",}".
out = out.replace(/,\}/g, '}');

const header = '/* Subset of Font Awesome Free 6.7.2 all.min.js: only the icons this site uses.\n' +
  '   Generated by tools/fa-subset.js; do not edit. Icons kept: ' + [...found].sort().join(' ') + ' */\n';
fs.writeFileSync(OUT, header + out);

// Names that look like icons but aren't in the bundle: style/utility classes
// (fa-solid, fa-fw, fa-lg ...) are expected; anything else is a typo or an
// icon missing from Font Awesome Free.
const UTIL = /^(solid|regular|brands|light|thin|duotone|sharp|fw|xs|sm|lg|xl|2xs|2xl|\dx|10x|spin|pulse|beat|fade|bounce|flip|shake|stack|stack-1x|stack-2x|inverse|border|pull-left|pull-right|li|ul|rotate-\d+|rotate-by|flip-horizontal|flip-vertical|flip-both|layers|layers-text|layers-counter)$/;

// The loader every page runs: it loads the subset when every icon on the
// page is in it, else the full set, so an icon added without rerunning this
// script still shows (the page is just heavier until the subset catches up).
const LOADER = path.join(ROOT, 'assets/js/fa-loader.js');
fs.writeFileSync(LOADER, `/* Generated by tools/fa-subset.js; do not edit.
   Loads icons.min.js (only the icons below) when every icon on the page is
   in it, otherwise the full all.min.js, so a newly added icon always shows. */
(function () {
  var HAVE = ${JSON.stringify([...found].sort())};
  var UTIL = ${UTIL.toString()};
  var me = document.currentScript;
  var full = false;
  var els = document.querySelectorAll('[class*="fa-"]');
  for (var i = 0; i < els.length && !full; i++) {
    var cls = (els[i].getAttribute('class') || '').split(/\\s+/);
    for (var j = 0; j < cls.length; j++) {
      if (cls[j].indexOf('fa-') !== 0) continue;
      var name = cls[j].slice(3);
      if (!UTIL.test(name) && HAVE.indexOf(name) === -1) { full = true; break; }
    }
  }
  var s = document.createElement('script');
  s.src = me.getAttribute(full ? 'data-full' : 'data-subset');
  document.head.appendChild(s);
})();
`);
const missing = [...wanted].filter(n => !found.has(n) && !UTIL.test(n)).sort();

const kb = n => Math.round(n / 1024) + ' KB';
console.log(`icons kept: ${kept}, dropped: ${dropped}`);
console.log(`size: ${kb(src.length)} -> ${kb(header.length + out.length)}`);
console.log('kept: ' + [...found].sort().join(' '));
if (missing.length) console.log('NOT FOUND (check spelling or add to EXTRA): ' + missing.join(' '));
